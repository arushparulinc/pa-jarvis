-- CREATE CONFIG TABLES

CREATE TABLE IF NOT EXISTS config.agents
(
    agent_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    agent_name character varying(200) COLLATE pg_catalog."default" NOT NULL,
    agent_description text COLLATE pg_catalog."default" NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
