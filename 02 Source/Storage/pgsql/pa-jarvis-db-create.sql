CREATE TABLE IF NOT EXISTS config.tools_registry
(
    tool_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    tool_name character varying(200) COLLATE pg_catalog."default" NOT NULL,
    tool_description text COLLATE pg_catalog."default" NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    agent_id bigint,
    CONSTRAINT tools_registry_pkey PRIMARY KEY (tool_id),
    CONSTRAINT tools_registry_tool_name_key UNIQUE (tool_name),
    CONSTRAINT tools_registry_agent_id_fkey FOREIGN KEY (agent_id)
        REFERENCES config.agents (agent_id) MATCH SIMPLE
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

ALTER TABLE IF EXISTS config.tools_registry OWNER to postgres;

GRANT ALL ON TABLE config.tools_registry TO :pgsql_user;

GRANT ALL ON TABLE config.tools_registry TO postgres;


CREATE TABLE IF NOT EXISTS config.tools_parameters
(
    param_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    tool_id bigint,
    param_name character varying(200) COLLATE pg_catalog."default" NOT NULL,
    param_type character varying(50) COLLATE pg_catalog."default" NOT NULL,
    param_description text COLLATE pg_catalog."default" NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tool_parameters_pkey PRIMARY KEY (param_id),
    CONSTRAINT tool_parameters_tool_id_param_name_key UNIQUE (tool_id, param_name),
    CONSTRAINT tool_parameters_tool_id_fkey FOREIGN KEY (tool_id)
        REFERENCES config.tools_registry (tool_id) MATCH SIMPLE
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

ALTER TABLE IF EXISTS config.tools_parameters OWNER to postgres;

GRANT ALL ON TABLE config.tools_parameters TO :pgsql_user;

GRANT ALL ON TABLE config.tools_parameters TO postgres;


